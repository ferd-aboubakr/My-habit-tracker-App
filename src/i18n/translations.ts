export type Language = 'fr' | 'en';
export type Currency = 'MAD' | 'EUR' | 'USD';

export interface CurrencyConfig {
  code: Currency;
  symbol: string;
  label: string;
  position: 'after' | 'before';
}

export const CURRENCIES: Record<Currency, CurrencyConfig> = {
  MAD: {
    code: 'MAD',
    symbol: 'DH',
    label: 'Dirham Marocain (MAD / DH)',
    position: 'after',
  },
  EUR: {
    code: 'EUR',
    symbol: '€',
    label: 'Euro (€)',
    position: 'after',
  },
  USD: {
    code: 'USD',
    symbol: '$',
    label: 'Dollar US ($)',
    position: 'before',
  },
};

export const formatCurrency = (amount: number, currency: Currency): string => {
  const cfg = CURRENCIES[currency] || CURRENCIES.MAD;
  const numStr = amount.toLocaleString();
  return cfg.position === 'after' ? `${numStr} ${cfg.symbol}` : `${cfg.symbol}${numStr}`;
};

